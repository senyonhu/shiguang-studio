def validate_options(kind: str, options: dict) -> dict:
    if kind == 'minigame':
        from .minigame_qa import validate_minigame_options
        return validate_minigame_options(options)
    allowed = {"check": set(), "preview": {"frame_ids"}, "routes": {"max_routes", "include_interactions", "minigame_scenarios"}, "build": {"max_routes", "include_interactions", "minigame_scenarios"}}
    if kind not in allowed or not isinstance(options, dict) or set(options) - allowed[kind]:
        raise BridgeError("INVALID_JOB_OPTIONS", "该任务包含不支持的参数", kind=kind)
    result = dict(options)
    if kind == "preview":
        ids = result.get("frame_ids")
        if not isinstance(ids, list) or not ids or len(ids) > 100 or any(not isinstance(fid, str) for fid in ids) or len(ids) != len(set(ids)):
            raise BridgeError("INVALID_JOB_OPTIONS", "预览需要1至100个不重复的frame_ids")
    if kind in {"routes", "build"}:
        count = result.get("max_routes", 256)
        if type(count) is not int or not 1 <= count <= 256:
            raise BridgeError("INVALID_JOB_OPTIONS", "max_routes应为1至256整数")
        result["max_routes"] = count
        if 'minigame_scenarios' in result:
            from .minigame_qa import validate_minigame_options, MAX_SCENARIOS
            scenarios = result['minigame_scenarios']
            if not isinstance(scenarios, list) or not 1 <= len(scenarios) <= MAX_SCENARIOS:
                raise BridgeError('INVALID_JOB_OPTIONS', '小游戏验收场景需要1至1024条，每批64条')
            result['minigame_scenarios'] = [validate_minigame_options(value) for value in scenarios]
        if type(result.get("include_interactions", False)) is not bool:
            raise BridgeError("INVALID_JOB_OPTIONS", "include_interactions应为布尔值")
    return result


def enumerate_routes(project: Project, max_routes: int = 256) -> list[list[dict]]:
    """Enumerate finite paths without Python recursion or silent truncation."""
    if not project.entry_frame_id:
        raise BridgeError("EMPTY_PROJECT", "作品尚无入口帧")
    pending = [(project.entry_frame_id, [], frozenset())]
    routes = []
    while pending:
        fid, path, seen = pending.pop()
        if fid in seen:
            raise BridgeError("ROUTE_CYCLE", "当前路线存在循环，需要有限测试范围", frame_id=fid)
        frame = project.frames[fid]
        node = {"frame_id": fid}
        seen = seen | {fid}
        if frame.flow.kind == "end":
            routes.append(path + [node])
            if len(routes) > max_routes:
                raise BridgeError("ROUTE_LIMIT", "路线数量超出本次上限，未声称穷举通过", max_routes=max_routes)
        elif frame.flow.kind == "next":
            pending.append((frame.flow.target_frame_id, path + [node], seen))
        elif frame.flow.kind == 'minigame':
            edges = [(branch.branch_id, branch.outcome, branch.target_frame_id) for branch in frame.flow.result_branches]
            edges += [('cancel', 'cancel', frame.flow.cancel_target_frame_id),
                      ('error', 'error', frame.flow.error_target_frame_id),
                      ('fallback', 'fallback', frame.flow.fallback_target_frame_id)]
            for branch_id, outcome, target in reversed(edges):
                pending.append((target, path + [{**node, 'minigame_branch_id': branch_id, 'outcome': outcome}], seen))
        else:
            for choice in reversed(frame.flow.choices):
                pending.append((choice.target_frame_id, path + [{**node, "choice_id": choice.choice_id}], seen))
    return routes


def _q(value) -> str:
    return json.dumps(value, ensure_ascii=False)


def _assert_frame(project, fid, lines, screenshot):
    frame = project.frames[fid]
    # The test runner also advances during window/scene transitions. Wait for
    # the actual native interaction text, not the label's early identity.
    readiness = f"rb_current_frame_id == {_q(fid)}"
    if frame.dialogue:
        readiness += f' and _rb_qa_visible_text() == {_q(frame.dialogue.text)}'
    else:
        readiness += ' and not renpy.get_screen("say")'
    if frame.flow.kind == "choices":
        readiness += ' and renpy.get_screen("choice") is not None'
    lines += [f"    pause 0.1 until eval ({readiness})", f"    pause {frame.transition.duration + 0.25 if frame.transition.kind != 'none' else 0.25}", f"    assert eval (rb_current_frame_id == {_q(fid)})"]
    for layer, components in [("rb_background", [frame.bg] if frame.bg else []), ("rb_characters", frame.characters), ("rb_decorations", frame.decorations)]:
        tags = ["rb_component_" + hashlib.sha256(item.component_id.encode()).hexdigest()[:24] for item in components]
        lines.append(f"    assert eval (set(renpy.get_showing_tags(layer={_q(layer)})) == set({_q(tags)}))")
    if frame.dialogue:
        lines += ['    assert screen "say"', f'    assert eval _rb_qa_assert_text({_q(frame.dialogue.text)})']
    else:
        lines.append('    assert not screen "say"')
    if frame.flow.kind == "choices":
        lines.append('    assert screen "choice"')
    lines.append(f"    assert eval (quick_menu == {frame.dialogue is not None or frame.flow.kind == 'choices'})")
    lines.append(f"    screenshot {_q(screenshot)}")


def native_tests(project: Project, kind: str, options: dict) -> tuple[str, dict]:
    calls = [frame.frame_id for frame in project.frames.values() if frame.flow.kind == 'minigame']
    if calls and kind != 'preview':
        raise BridgeError('MINIGAME_PLAYTHROUGH_REQUIRED', 'HTML路线需要真实输入的有界场景；请先逐调用使用test_minigame，普通路线测试不能静默跳过小游戏', frame_ids=calls)
    if calls and kind == 'preview' and set(calls) & set(options.get('frame_ids', [])):
        raise BridgeError('MINIGAME_PREVIEW_REQUIRES_SESSION', '小游戏调用须用test_minigame打开真实宿主并检查返回；单帧截图不能替代小游戏交互')
    lines = ["# Fixed native QA harness; not used in ordinary gameplay.", NATIVE_QA_SOURCE, "testsuite global:", "    teardown:", "        exit", ""]
    mapping = {}
    if kind == "preview":
        unknown = set(options["frame_ids"]) - set(project.frames)
        if unknown:
            raise BridgeError("FRAME_NOT_FOUND", "预览目标不存在", frame_ids=sorted(unknown))
        for number, fid in enumerate(options["frame_ids"]):
            case = f"preview_{number:04d}"
            shot = f"{case}_{fid}"
            lines += [f"testcase {case}:", "    $ _test.timeout = 20.0", "    $ _preferences.text_cps = 0"]
            if number:
                lines.append("    run MainMenu(confirm=False)")
            lines += ["    run Start()", f"    run Jump({_q(stable_label(fid))})"]
            _assert_frame(project, fid, lines, shot)
            lines.append("")
            mapping[shot] = {"frame_id": fid, "case": case, "scope": "isolated_frame"}
        return "\n".join(lines), {"screenshots": mapping, "route_coverage": None}
    routes = enumerate_routes(project, options.get("max_routes", 256))
    edge_coverage = set()
    for index, route in enumerate(routes):
        case = f"route_{index:04d}"
        lines += [f"testcase {case}:", "    $ _test.timeout = 20.0", "    $ _preferences.text_cps = 0", "    run Start()"]
        for number, step in enumerate(route):
            fid = step["frame_id"]
            frame = project.frames[fid]
            shot = f"{case}_{number:05d}_{fid}"
            _assert_frame(project, fid, lines, shot)
            mapping[shot] = {"frame_id": fid, "case": case, "scope": "from_start", "step": number}
            if frame.flow.kind == "choices":
                choice = next(item for item in frame.flow.choices if item.choice_id == step["choice_id"])
                # Native menu button selection. Ambiguous duplicate captions
                # are rejected rather than selecting an arbitrary branch.
                if len({item.text for item in frame.flow.choices}) != len(frame.flow.choices):
                    raise BridgeError("AMBIGUOUS_CHOICE_TEXT", "原生自动测试需要该帧选项显示文字不同", frame_id=fid)
                lines.append(f"    click {_q(choice.text)}")
                edge_coverage.add((fid, choice.choice_id, choice.target_frame_id))
            elif frame.flow.kind == "next":
                lines.append('    keysym "dismiss"')
                edge_coverage.add((fid, "next", frame.flow.target_frame_id))
            else:
                lines += ['    keysym "dismiss"', '    pause 0.25', '    assert screen "main_menu"']
        lines.append("")
    interactions = {"requested": options.get("include_interactions", False), "cases": []}
    if interactions["requested"]:
        first = project.frames[project.entry_frame_id]
        second = project.frames.get(first.flow.target_frame_id) if first.flow.kind == "next" else None
        if (not first.dialogue or not second or not second.dialogue or second.flow.kind == "choices"):
            raise BridgeError("INTERACTION_FIXTURE_REQUIRED", "交互测试需要入口的前两帧为直接相连的普通对白帧")
        lines.append(interaction_testcases(first.frame_id, second.frame_id,
                                          first_text=first.dialogue.text, second_text=second.dialogue.text))
        interactions["cases"] = ["save_load_rollback", "history_and_preferences", "auto_forward", "skip"]
    return "\n".join(lines), {"screenshots": mapping, "native_interactions": interactions,
        "route_coverage": {"routes": routes, "route_count": len(routes), "edges": [list(edge) for edge in sorted(edge_coverage)], "frame_ids": sorted({step["frame_id"] for route in routes for step in route}), "entry_mode": "Start", "complete_for_finite_graph": True}}


def _code_digest() -> str:
    files = sorted(Path(__file__).parent.rglob("*.py"))
    return digest({path.name: file_hash(path) for path in files})


def _map_errors(text: str, source_map: dict, project: Project) -> list[dict]:
    diagnostics = []
    for filename, number in re.findall(r'File "([^"\r\n]+)", line (\d+)', text):
        number = int(number)
        matched = next((entry for entry in source_map["frames"].values() if Path(filename).name == Path(entry["file"]).name and entry["start_line"] <= number <= entry["end_line"]), None)
        diagnostics.append({"file": filename, "line": number, "frame_id": matched["frame_id"] if matched else None, "act_id": matched["act_id"] if matched else None, "provenance": project.frames[matched["frame_id"]].provenance if matched else None})
    return diagnostics


def _path_units(path: Path) -> int:
    """Windows MAX_PATH counts UTF-16 units, including the trailing NUL."""
    return len(str(path).encode("utf-16-le")) // 2


def _short_paths(paths) -> int:
    maximum = 0
    for path in paths:
        path = path.resolve()
        units = _path_units(path)
        maximum = max(maximum, units)
        if units >= 260:
            raise BridgeError("RELEASE_PATH_BUDGET", "发行临时路径超出Windows路径限制", path=str(path), utf16_units=units, limit_exclusive=260)
    return maximum


def _regular_entry(path: Path):
    info = path.lstat()
    if stat.S_ISLNK(info.st_mode) or getattr(info, "st_file_attributes", 0) & 0x400:
        raise BridgeError("RELEASE_PATH_INVALID", "发行工程不允许链接或重解析点", path=str(path))
    if not (stat.S_ISDIR(info.st_mode) or stat.S_ISREG(info.st_mode)):
        raise BridgeError("RELEASE_PATH_INVALID", "发行工程包含非普通文件", path=str(path))
    return info


def _tree_entries(root: Path):
    root = root.absolute()
    _regular_entry(root)
    canonical = root.resolve()
    for current, directories, names in os.walk(root, followlinks=False):
        for name in sorted(directories + names):
            path = Path(current) / name
            info = _regular_entry(path)
            if not path.resolve().is_relative_to(canonical):
                raise BridgeError("RELEASE_PATH_INVALID", "发行工程文件越出受管目录", path=str(path))
            yield path, info


def _tree_manifest(root: Path) -> dict:
    root = root.absolute()
    files = {}
    for path, info in _tree_entries(root):
        if stat.S_ISREG(info.st_mode):
            files[path.relative_to(root).as_posix()] = {"sha256": file_hash(path), "bytes": info.st_size}
    return dict(sorted(files.items()))


def _copy_verified_tree(source: Path, destination: Path, *, short: bool = False) -> dict:
    """Copy every file and empty directory; verify source and destination bytes."""
    before = _tree_manifest(source)
    if short:
        _short_paths([destination, *(destination / path.relative_to(source) for path, _ in _tree_entries(source))])
    shutil.copytree(source, destination)
    # Creation can redirect Windows Store paths. Validate the actual paths too.
    if short:
        _short_paths([destination, *(path for path, _ in _tree_entries(destination))])
    copied = _tree_manifest(destination)
    if copied != before or _tree_manifest(source) != before:
        raise BridgeError("RELEASE_COPY_MISMATCH", "发行复制前后文件哈希不一致", source=str(source), destination=str(destination))
    return copied


def _manifest_evidence(evidence: Path, name: str, files: dict) -> dict:
    path = evidence / name
    atomic_json(path, {"files": files, "tree_sha256": digest(files)})
    return {"path": str(path), "sha256": file_hash(path), "tree_sha256": digest(files), "file_count": len(files)}


def _visual_environment(project: Project, generation: dict, engine_log: Path, screenshots: list[dict]) -> dict:
    """Bind the logical canvas and actual native screenshot size separately."""
    if not engine_log.is_file():
        raise BridgeError("VISUAL_ENVIRONMENT_UNAVAILABLE", "实际SDK renderer日志缺失")
    text = engine_log.read_text(encoding="utf-8", errors="replace")
    backend = re.search(r"^Initializing ([a-zA-Z0-9_]+) renderer:\s*$", text, re.MULTILINE)
    fields = {name: re.search(r"^" + name + r":\s*(.+)$", text, re.MULTILINE)
              for name in ("Vendor", "Renderer", "Version")}
    if backend is None or any(value is None for value in fields.values()):
        raise BridgeError("VISUAL_ENVIRONMENT_UNAVAILABLE", "实际SDK日志缺少可比较的renderer信息")
    font = Path(generation["project_path"]) / "game/SourceHanSansLite.ttf"
    actual_hash = file_hash(font)
    manifest = read_json(Path(generation["manifest_path"]))
    if actual_hash != manifest.get("chinese_font_sha256"):
        raise BridgeError("ASSET_HASH_MISMATCH", "视觉基准字体与生成清单不一致")
    if not screenshots:
        raise BridgeError("VISUAL_ENVIRONMENT_UNAVAILABLE", "实际原生截图缺失，不能推测截图尺寸")
    capture_sizes = set()
    for entry in screenshots:
        try:
            data = Path(entry["path"]).read_bytes()
            if hashlib.sha256(data).hexdigest() != entry["sha256"]:
                raise BridgeError("VISUAL_IMAGE_CHANGED", "截图与实际预览哈希不同", path=entry["path"])
            with Image.open(io.BytesIO(data)) as captured:
                if captured.format != "PNG":
                    raise ValueError("Native capture is not PNG")
                captured.load()
                capture_sizes.add(captured.size)
        except BridgeError:
            raise
        except (OSError, ValueError, KeyError, TypeError) as error:
            raise BridgeError("VISUAL_ENVIRONMENT_UNAVAILABLE", "实际原生截图缺失或损坏") from error
    if len(capture_sizes) != 1:
        raise BridgeError("VISUAL_ENVIRONMENT_UNAVAILABLE", "同一预览的实际截图尺寸不一致", capture_sizes=sorted(capture_sizes))
    return {"sdk_version": generation["sdk_version"], "language": project.language,
            "renderer": {"backend": backend.group(1), **{name.lower(): match.group(1).strip() for name, match in fields.items()}},
            "resolution": [project.canvas.width, project.canvas.height],
            "capture_resolution": list(next(iter(capture_sizes))), "capture_resolution_verified": True,
            "font_sha256": actual_hash}


@contextmanager
def _short_release_workspace(report: dict, evidence: Path):
    """Own one minted directory; never delete an unchecked path or a link."""
    temporary_parent = Path(tempfile.gettempdir())
    # A drive-root temporary directory avoids Store's redirected, deep TEMP.
    # Permission-limited hosts may use TEMP, with the same actual-path checks.
    parents = [Path(temporary_parent.anchor), temporary_parent] if os.name == "nt" else [temporary_parent]
    root = None
    for parent in dict.fromkeys(parents):
        try:
            requested = Path(tempfile.mkdtemp(prefix="rb-", dir=parent))
            root = requested.resolve()
            break
        except PermissionError:
            continue
    if root is None:
        raise BridgeError("RELEASE_STAGING_UNAVAILABLE", "无法创建受管发行临时目录")
    identity = _regular_entry(root)
    token = uuid.uuid4().hex
    marker = root / ".bridge-release-owner"
    marker.write_text(token, encoding="ascii")
    stage = {"requested_directory": str(requested), "canonical_directory": str(root),
             "project_directory": str(root / "g"), "output_directory": str(root / "o"),
             "independent_directory": str(root / "i"), "path_limit_exclusive": 260,
             "cleanup": {"status": "pending"},
             "cleanup_scope": "finally_on_normal_return_or_exception; forced_worker_termination_not_guaranteed"}
    report["release_staging"] = stage
    had_error = False
    try:
        _short_paths([root, marker])
        yield root, stage
    except BaseException:
        had_error = True
        raise
    finally:
        try:
            current = _regular_entry(requested)
            if requested.resolve() != root or (current.st_dev, current.st_ino) != (identity.st_dev, identity.st_ino):
                raise BridgeError("RELEASE_CLEANUP_UNSAFE", "发行临时目录身份改变，拒绝清理")
            _regular_entry(marker)
            if marker.read_text(encoding="ascii") != token:
                raise BridgeError("RELEASE_CLEANUP_UNSAFE", "发行临时目录所有权标记改变，拒绝清理")
            for _ in _tree_entries(root):
                pass  # Refuse nested links before recursive deletion, without reading package bytes again.
            shutil.rmtree(root)
            stage["cleanup"] = {"status": "removed", "directory_exists": root.exists(), "ownership_verified": True}
        except Exception as error:
            stage["cleanup"] = {"status": "failed", "directory_exists": root.exists(), "error": str(error)}
            if not had_error:
                report.update(ok=False, status="failed", error={"code": "RELEASE_CLEANUP_FAILED", "message": "发行临时目录未安全清理", "details": stage["cleanup"]})
        atomic_json(evidence / "pipeline-progress.json", report)
        if stage["cleanup"]["status"] != "removed" and not had_error:
            raise BridgeError("RELEASE_CLEANUP_FAILED", "发行临时目录未安全清理", **stage["cleanup"])


def _extract_verified_package(package: Path, independent: Path) -> tuple[list[str], dict, int]:
    independent.mkdir()
    independent = independent.resolve()
    members, destinations = {}, set()
    maximum = _short_paths([independent])
    with zipfile.ZipFile(package) as archive:
        names = archive.namelist()
        for item in archive.infolist():
            # ZIP names use POSIX separators. Backslashes/ADS are unsafe on Windows.
            original_name = item.orig_filename
            if "\\" in original_name or ":" in original_name or "\x00" in original_name or ".." in original_name.split("/"):
                raise BridgeError("PACKAGE_PATH_INVALID", "发行包包含无效路径", member=item.filename)
            destination = (independent / item.filename).resolve()
            mode = item.external_attr >> 16
            if not destination.is_relative_to(independent) or destination == independent or stat.S_ISLNK(mode):
                raise BridgeError("PACKAGE_PATH_INVALID", "发行包有目录越界或链接条目", member=item.filename)
            relative = destination.relative_to(independent).as_posix()
            folded = relative.casefold()
            if folded in destinations:
                raise BridgeError("PACKAGE_PATH_INVALID", "发行包包含重复目标路径", member=item.filename)
            destinations.add(folded)
            maximum = max(maximum, _short_paths([destination]))
            if not item.is_dir():
                with archive.open(item) as stream:
                    member_hash = hashlib.file_digest(stream, "sha256").hexdigest()
                members[relative] = {"sha256": member_hash, "bytes": item.file_size}
        archive.extractall(independent)
    members = dict(sorted(members.items()))
    if _tree_manifest(independent) != members:
        raise BridgeError("PACKAGE_COPY_MISMATCH", "发行包解压文件与ZIP成员哈希不一致")
    return names, members, maximum


def _verify_package_cache_policy(members: dict) -> dict:
    """Prove regenerable caches were excluded, without exempting any member SHA."""
    names = set(members)
    forbidden = []
    for name in names:
        parts = name.split("/")
        relative = "/".join(parts[1:])
        if relative in {"game/cache/py3analysis.rpyb", "game/cache/screens.rpyb"} or re.fullmatch(r"game/cache/bytecode-\d+\.rpyb", relative):
            forbidden.append(name)
        if len(parts) > 3 and parts[1] == "renpy" and parts[-2] == "__pycache__":
            match = re.fullmatch(r"(.+)\.cpython-\d+(?:\.opt-\d+)?\.pyc", parts[-1])
            if match and "/".join([*parts[:-2], match.group(1) + ".py"]) in names:
                forbidden.append(name)
    if forbidden:
        raise BridgeError("PACKAGE_CACHE_PRESENT", "发行包仍包含可重新生成的引擎缓存", members=sorted(forbidden))
    return {"verified": True, "game_cache_policy": "exclude bytecode-<version>.rpyb, py3analysis.rpyb and screens.rpyb",
            "engine_python_cache_policy": "exclude only renpy __pycache__ .pyc with an exact SDK .py source",
            "immutable_member_policy": "every retained ZIP member must remain byte-identical after package QA"}


def _minigame_required_members(manifest, config):
    """Include immutable historical packages and all frozen native dependencies."""
    required = {}
    def add_tree(relative, files):
        for name, expected in files.items():
            path = relative + '/' + name
            if (path.startswith('/') or '\\' in path or ':' in path
                    or any(part in {'', '.', '..'} for part in path.split('/'))
                    or not isinstance(expected, dict) or not re.fullmatch(r'[0-9a-f]{64}', expected.get('sha256', ''))
                    or type(expected.get('bytes')) is not int or expected['bytes'] < 0):
                raise BridgeError('MINIGAME_RELEASE_MANIFEST_INVALID', '发行资源清单不合法', path=path)
            if path in required and required[path] != expected:
                raise BridgeError('MINIGAME_RELEASE_MEMBER_CONFLICT', '同一个发行路径声明了不同内容', path=path)
            required[path] = dict(expected)
    for games in (manifest.get('minigames', {}), config.get('minigames', {}), config.get('retained_games', {})):
        for game in games.values():
            add_tree(game['package_root'], game['files'])
    for section in ('host', 'fixed_runtime'):
        runtime = config.get(section) or {}
        if runtime:
            relative = runtime.get('relative_root')
            if not relative:
                executable = runtime.get('relative_executable')
                if not executable:
                    raise BridgeError('MINIGAME_RELEASE_MANIFEST_INVALID', '宿主资源缺少实际相对启动路径')
                relative = Path(executable).parent.as_posix()
            add_tree(relative, runtime.get('files', {}))
    return required


def _build_release(target, release, generation, sdk, timeout, record, report, evidence, *,
                   minigame_project=None, minigame_scenarios=None):
    """SDK and package QA run in short paths; published bytes remain managed."""
    manifest = read_json(Path(generation['manifest_path'])) if 'manifest_path' in generation else {}
    minigames = manifest.get('minigames', {})
    prefix = ''
    if minigames:
        # Rules precede global .txt/.log exclusions. WebView2 reads loose files.
        prefix = '''init -10 python:
    build.early_base_patterns[0:0] = [
        ("game/bridge_minigames/**", ["all"]),
        ("game/bridge-minigames.json", ["all"]),
        ("game/python-packages/renpy_bridge_minigames/**", ["all"]),
        ("html-runtime/**", ["all"]),
    ]
'''
    (target / "game/bridge_build.rpy").write_text(prefix + RELEASE_BUILD_SOURCE, encoding="utf-8")
    from .derived_integrity import record_derived_sources
    report.setdefault("generation", generation)["derived_sources"] = record_derived_sources(target, controlled_paths=["game/bridge_build.rpy"])
    release.mkdir(parents=True)
    with _short_release_workspace(report, evidence) as (work, stage):
        staged_project, output, independent = work / "g", work / "o", work / "i"
        copied = _copy_verified_tree(target, staged_project, short=True)
        stage["source_manifest"] = _manifest_evidence(evidence, "release-source-files.json", copied)
        stage["source_directory"] = str(target)
        stage["source_copy_verified"] = True
        stage["project_max_path_utf16_units"] = _short_paths([staged_project, *(staged_project / name for name in copied)])
        output.mkdir()
        saves = work / "s"
        saves.mkdir()
        env = {"RENPY_MULTIPERSISTENT": str(work / "m")}
        stage["savedir"] = str(saves)
        stage["multipersistent"] = env["RENPY_MULTIPERSISTENT"]
        atomic_json(evidence / "pipeline-progress.json", report)
        if not record("distribute", run_sdk(sdk, "launcher", "distribute", [str(staged_project), "--destination", str(output), "--package", "pc", "--no-update", "--savedir", str(saves)], timeout_seconds=600, env=env), staged_project):
            return False
        zips = list(output.glob("*.zip"))
        if len(zips) != 1:
            raise BridgeError("PACKAGE_MISSING", "发行任务没有产出唯一PC包", packages=[str(path) for path in zips])
        staged_package = zips[0]
        _short_paths([staged_package])
        names, members, maximum = _extract_verified_package(staged_package, independent)
        stage["package_max_path_utf16_units"] = maximum
        member_evidence = _manifest_evidence(evidence, "release-package-members.json", members)
        stage["cache_exclusion"] = _verify_package_cache_policy(members)
        exes = [path for path in independent.rglob("*.exe") if path.name == generation["build_name"] + ".exe"]
        if len(exes) != 1:
            raise BridgeError("PACKAGE_EXECUTABLE_MISSING", "包内Windows启动程序不唯一")
        exe = exes[0]
        if minigames:
            config = read_json(target / 'game/bridge-minigames.json')
            required_files = _minigame_required_members(manifest, config)
            required_files['game/bridge-minigames.json'] = {'sha256': file_hash(target / 'game/bridge-minigames.json'), 'bytes': (target / 'game/bridge-minigames.json').stat().st_size}
            missing = []
            for name, expected in required_files.items():
                path = exe.parent / name
                if not path.is_file() or file_hash(path) != expected['sha256'] or path.stat().st_size != expected['bytes']:
                    missing.append(name)
            if missing:
                raise BridgeError('MINIGAME_RELEASE_FILES_MISSING', '发行包缺少或改变HTML、许可、宿主或固定浏览器文件', paths=missing)
            report['minigame_package_members'] = {'verified': True, 'file_count': len(required_files), 'all_declared_files_included': True,
                                                 'retained_package_count': len(config.get('retained_games', {})), 'old_player_save_verified': False}
        package_saves = work / "p"
        package_saves.mkdir()
        execution = {"actually_tested_executable": str(exe), "actually_tested_directory": str(exe.parent),
                     "actually_tested_executable_sha256": file_hash(exe), "package_members_manifest": member_evidence,
                     "savedir": str(package_saves), "multipersistent": env["RENPY_MULTIPERSISTENT"], "status": "running"}
        report["execution"] = execution
        if minigames:
            from .minigame_qa import prepare_scenario_suite, run_scenario_suite
            _, package_scenarios, _ = prepare_scenario_suite(minigame_project, minigame_scenarios, exe.parent, package_saves)
            report['minigame_package_verification'] = run_scenario_suite(sdk, exe.parent, env, package_scenarios, evidence / 'package-html', executable=exe)
            package_passed = report['minigame_package_verification']['passed']
        else:
            package_passed = record("package-tests", _execute([str(exe), str(exe.parent), "test", "--report-detailed", "--savedir", str(package_saves)], exe.parent, timeout, env), exe.parent)
        if not package_passed:
            execution["status"] = "failed"
            return False
        tested = _tree_manifest(independent)
        stage["tested_max_path_utf16_units"] = _short_paths([independent, *(path for path, _ in _tree_entries(independent))])
        execution["tested_tree_manifest"] = _manifest_evidence(evidence, "release-tested-files.json", tested)
        changed = [{"path": name, "before": item, "after": tested.get(name)} for name, item in members.items() if tested.get(name) != item]
        if changed:
            error = BridgeError("PACKAGE_RUNTIME_MUTATION", "包内测试修改了发行ZIP原始成员", changed_members=changed,
                                tested_tree_manifest=execution["tested_tree_manifest"])
            execution.update(status="failed", package_members_unchanged=False, changed_package_members=changed)
            report.update(ok=False, status="failed", error=error.as_dict()["error"])
            raise error
        execution["package_members_unchanged"] = True
        published_package = release / staged_package.name
        shutil.copy2(staged_package, published_package)
        if file_hash(published_package) != file_hash(staged_package):
            raise BridgeError("RELEASE_COPY_MISMATCH", "发行ZIP发布哈希不一致")
        published_independent = release / "independent"
        published = _copy_verified_tree(independent, published_independent)
        published_exe = published_independent / exe.relative_to(independent)
        execution.update(status="passed", published_executable=str(published_exe), published_directory=str(published_exe.parent),
                         published_executable_sha256=file_hash(published_exe),
                         published_tree_manifest=_manifest_evidence(evidence, "release-published-files.json", published),
                         tested_tree_sha256=digest(tested), published_tree_sha256=digest(published),
                         tested_and_published_identical=tested == published)
        if _tree_manifest(target) != copied:
            raise BridgeError("RELEASE_SOURCE_MUTATION", "发行期间原始生成工程发生变化")
        stage["source_unchanged"] = True
        stage["staged_package"] = {"path": str(staged_package), "sha256": file_hash(staged_package), "bytes": staged_package.stat().st_size}
        if report.get("interaction_verification"):
            report["interaction_verification"]["independent_package_status"] = "passed"
        report["release"] = {"path": str(published_package), "sha256": file_hash(published_package), "bytes": published_package.stat().st_size, "entries": len(names), "executable": str(published_exe), "executable_sha256": file_hash(published_exe), "independent_directory": str(published_exe.parent), "qa_harness_included": True}
        report["independent_release_verified"] = True
        report["package_screenshots"] = [{"path": str(path), "sha256": file_hash(path)} for path in (published_exe.parent / "tests/screenshots").glob("*.png")]
    return True


def execute_job(store: Store, job: dict) -> dict:
    options = validate_options(job["kind"], job["options"])
    project = store.load(job["project_id"], job["revision"])
    lock_path = store.home / "runtimes/sdk-lock.json"
    if not lock_path.exists():
        raise BridgeError("SDK_NOT_CONFIGURED", "没有固定SDK运行配置")
    lock = read_json(lock_path)
    sdk = discover_sdk(store.home / lock["relative_path"])
    if sdk.version != lock["version"]:
        raise BridgeError("SDK_VERSION_MISMATCH", "SDK实际版本与固定配置不同", expected=lock["version"], actual=sdk.version)
    root = store.directory(project.project_id)
    evidence = store.home / "jobs" / job["job_id"]
    target = root / "generated" / f"r{project.revision:08d}" / job["job_id"]
    report = {"ok": False, "status": "running", "job_id": job["job_id"], "kind": job["kind"], "project_id": project.project_id, "revision": project.revision, "started_at": now(), "code_digest": _code_digest(), "model_hash": digest(project.model_dump(mode="json")), "schema_version": project.schema_version, "generator_version": GENERATOR_VERSION, "sdk_version": sdk.version, "commands": {}, "screenshots": [], "visual_review": "not_run", "audio_output_verification": "not_run", "independent_release_verified": False}
    started = time.monotonic()
    def ensure_source_stable():
        current = _code_digest()
        report['code_digest_end'] = current
        report['source_stable_during_job'] = current == report['code_digest']
        if not report['source_stable_during_job']:
            raise BridgeError('SOURCE_CHANGED_DURING_JOB', '验收期间制作服务源码发生变化，须用冻结版本重验；保留此前可运行版本')
    flow = analyze_flow(project)
    report["flow"] = flow
    if not project.frames:
        raise BridgeError("EMPTY_PROJECT", "作品没有可检查的帧")
    if flow["without_exit"]:
        raise BridgeError("FLOW_WITHOUT_EXIT", "流程中存在无法到达结局的帧", frame_ids=flow["without_exit"])
    uses_minigames = any(frame.flow.kind == 'minigame' for frame in project.frames.values())
    generation = generate_project(project, root, target, sdk, defer_minigame_integrity=True) if uses_minigames else generate_project(project, root, target, sdk)
    report["generation"] = generation
    previous = store.head(project.project_id).get("runnable_project_path")
    if previous:
        baseline = (root / previous).resolve()
        if not baseline.is_relative_to(root) or not baseline.is_dir():
            raise BridgeError("COMPATIBILITY_BASELINE_MISSING", "之前可运行工程路径无效")
        report["compatibility"] = prepare_previous_release(baseline, target, project.project_id, sdk.version)
    if uses_minigames:
        from .derived_integrity import record_derived_sources
        generation['derived_sources'] = record_derived_sources(target, managed_roots=generation['derived_sources']['managed_roots'])
    source_map = read_json(Path(generation["source_map_path"]))
    from .layout import check_layout
    report["layout"] = check_layout(project, root, target / "game/SourceHanSansLite.ttf")
    if not report["layout"]["ok"]:
        report.update(status="failed", error={"code": "LAYOUT_INVALID", "message": "字体或布局存在错误", "details": {"diagnostics": report["layout"]["diagnostics"]}})
        return report
    private = evidence / "private-state"
    saves = private / "saves"
    saves.mkdir(parents=True, exist_ok=True)
    env = {"RENPY_MULTIPERSISTENT": str(private / "multipersistent")}
    report["save_locations"] = {"savedir": str(saves), "multipersistent": env["RENPY_MULTIPERSISTENT"], "player_namespace": project.save_namespace}

    def record(name, result, engine_root=target):
        report["commands"][name] = asdict(result)
        for stream in ("stdout", "stderr"):
            (evidence / f"{name}.{stream}.txt").write_text(getattr(result, stream), encoding="utf-8")
        if (engine_root / "log.txt").is_file():
            shutil.copyfile(engine_root / "log.txt", evidence / f"{name}.engine-log.txt")
        passed = result.exit_code == 0 and not result.timed_out
        if name in {"native-tests", "package-tests"}:
            passed = passed and "[rpytest] Status: PASSED" in result.stdout + result.stderr
        if not passed:
            report.update(status="failed", error={"code": "SDK_TIMEOUT" if result.timed_out else "SDK_FAILED", "message": f"Ren'Py {name}未通过", "details": {"stage": name, "exit_code": result.exit_code}})
            report["diagnostics"] = _map_errors(result.stdout + result.stderr, source_map, project)
        atomic_json(evidence / "pipeline-progress.json", report)
        return passed

    qa = None
    prepared_minigame = None
    prepared_suite = None
    if job['kind'] == 'minigame':
        from .minigame_qa import prepare_qa
        prepared_minigame = prepare_qa(project, options, target, saves)
        script = prepared_minigame['source']
        qa = {'screenshots': {'minigame_native_waiting': {'frame_id': options['frame_id'], 'scope': 'isolated_minigame'},
                              'minigame_native_return': {'frame_id': options['expected_target_frame_id'], 'scope': 'actual_minigame_return'}},
              'route_coverage': {'entry_mode': 'Start' if options['from_entry'] else 'isolated_call',
                                 'complete_for_finite_graph': False, 'scope': 'one_declared_real_input_scenario'}}
    elif job['kind'] in {'routes', 'build'} and any(frame.flow.kind == 'minigame' for frame in project.frames.values()):
        from .minigame_qa import prepare_scenario_suite, validate_release_coverage
        if options.get('include_interactions'):
            raise BridgeError('INTERACTION_SCENARIOS_REQUIRED', 'HTML作品的存档回滚交互需要专门场景，不能套用纯剧情前两帧测试')
        if job['kind'] == 'build':
            report['minimum_minigame_release_coverage'] = validate_release_coverage(project, options.get('minigame_scenarios'))
        script, prepared_suite, coverage = prepare_scenario_suite(project, options.get('minigame_scenarios'), target, saves)
        qa = {'screenshots': {}, 'route_coverage': coverage}
    elif job["kind"] != "check":
        script, qa = native_tests(project, job["kind"] if job["kind"] == "preview" else "routes", options)
    if qa is not None:
        (target / "game/bridge_testcases.rpy").write_text(script, encoding="utf-8")
        from .derived_integrity import record_derived_sources
        report["generation"]["derived_sources"] = record_derived_sources(target, controlled_paths=["game/bridge_testcases.rpy"])
        report["testcases_sha256"] = file_hash(target / "game/bridge_testcases.rpy")
        report["route_coverage"] = qa["route_coverage"]
        if qa.get("native_interactions", {}).get("requested"):
            report["interaction_verification"] = {**qa["native_interactions"], "status": "not_run"}
    for command, args in [("compile", []), ("lint", ["--error-code"])]:
        if not record(command, run_sdk(sdk, target, command, [*args, "--savedir", str(saves)], timeout_seconds=120, env=env)):
            return report
    if qa:
        timeout = min(1800, max(120, len(qa["screenshots"]) * 2 + 60))
        if prepared_suite:
            from .minigame_qa import run_scenario_suite
            report['minigame_verification'] = run_scenario_suite(sdk, target, env, prepared_suite, evidence)
            native_passed = report['minigame_verification']['passed']
            if not native_passed:
                report.update(status='failed', error={'code': 'MINIGAME_QA_FAILED', 'message': '声明的真实HTML玩法场景未全部通过', 'details': {}})
        elif prepared_minigame:
            from .minigame_qa import run_actual_qa
            report['minigame_verification'] = run_actual_qa(sdk, target, saves, env, prepared_minigame, evidence)
            verification = report['minigame_verification']
            report['commands']['native-tests'] = verification['native']
            report['commands']['actual-browser-input'] = verification['browser']
            native_passed = verification['passed']
            if not native_passed:
                report.update(status='failed', error={'code': 'MINIGAME_QA_FAILED', 'message': '真实HTML输入或返回剧情断言未通过', 'details': {}})
        else:
            native_passed = record("native-tests", run_sdk(sdk, target, "test", ["--report-detailed", "--savedir", str(saves)], timeout_seconds=timeout, env=env))
        if not native_passed:
            if report.get("interaction_verification"):
                report["interaction_verification"]["status"] = "failed"
            return report
        if report.get("interaction_verification"):
            report["interaction_verification"]["status"] = "passed"
        for path in sorted((target / "tests/screenshots").glob("*.png")):
            if path.stem in qa["screenshots"]:
                report["screenshots"].append({**qa["screenshots"][path.stem], "path": str(path), "sha256": file_hash(path), "revision": project.revision})
        if len(report["screenshots"]) != len(qa["screenshots"]):
            report.update(status="failed", error={"code": "SCREENSHOT_INCOMPLETE", "message": "原生截图证据不完整", "details": {}})
            return report
        if job["kind"] == "preview":
            from .visual_regression import compare_preview
            try:
                report["visual_environment"] = _visual_environment(project, generation, evidence / "native-tests.engine-log.txt", report["screenshots"])
                report["visual_comparison"] = compare_preview(store, project, report)
            except BridgeError as exc:
                report["visual_comparison"] = {"ok": False, "status": "blocked", "error": exc.as_dict()["error"]}
            comparison_status = report["visual_comparison"]["status"]
            report["visual_review"] = "visual_" + comparison_status if comparison_status in {"failed", "blocked"} else comparison_status
        if job["kind"] == "routes":
            ensure_source_stable()
            store.mark_runnable(project.project_id, project.revision, target)
    if job["kind"] == "build":
        ensure_source_stable()
        release = root / "releases" / job["job_id"]
        build_passed = _build_release(target, release, generation, sdk, timeout, record, report, evidence,
            minigame_project=project if prepared_suite else None,
            minigame_scenarios=options.get('minigame_scenarios') if prepared_suite else None)
        if not build_passed:
            if report.get("status") == "running":
                report.update(status="failed", error={"code": "RELEASE_VERIFICATION_FAILED", "message": "独立发行构建或实际验收未通过", "details": {}})
            return report
        ensure_source_stable()
        store.mark_runnable(project.project_id, project.revision, target)
    ensure_source_stable()
    report.update(ok=True, status="passed", finished_at=now(), duration_seconds=time.monotonic() - started)
    atomic_json(evidence / "pipeline-progress.json", report)
    return report
